#!/usr/bin/env python3
"""Embeds a file in a C header as a NUL-terminated byte array.

usage: embed.py SOURCE OUTPUT NAME

Writes `static const char NAME[] = {...};` so the data can be used as a C
string (sizeof NAME - 1 is the file size).
"""

import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source, output, name = sys.argv[1:4]
    with open(source, "rb") as f:
        data = f.read()
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    with open(output + ".tmp", "w") as f:
        f.write(f"/* Generated by tools/embed.py from {source.split('/')[-1]}. Do not edit. */\n")
        f.write(f"static const char {name}[] = {{\n")
        f.write("\n".join(lines) + "\n    0x00,\n};\n")
    import os

    os.replace(output + ".tmp", output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
